import { build } from "esbuild";
import { readFile, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = dirname(fileURLToPath(import.meta.url));
const metadata = JSON.parse(await readFile(join(root, "package.json"), "utf8"));
for (const file of ["plugin.json", ".codex-plugin/plugin.json"]) {
  const manifest = JSON.parse(await readFile(join(root, file), "utf8"));
  if (manifest.name !== "classcue" || manifest.version !== metadata.version)
    throw new Error(`Plugin identity/version mismatch: ${file}`);
}
const options = { absWorkingDir: root, bundle: true, write: false, format: "esm",
  minify: true, legalComments: "inline", metafile: true, logLevel: "silent" };
const [server, app, template, icon] = await Promise.all([
  build({ ...options, entryPoints: ["server.mjs"], platform: "node", target: "node24",
    banner: { js: '// Generated by build.mjs. Do not edit.\nimport { createRequire } from "node:module"; const require = createRequire(import.meta.url);' } }),
  build({ ...options, entryPoints: ["app.mjs"], platform: "browser", target: "es2022" }),
  readFile(join(root, "view.html"), "utf8"),
  readFile(join(root, "icon.png")),
]);
const html = template.replace("CLASSCUE_ICON", `data:image/png;base64,${icon.toString("base64")}`)
  .replace("CLASSCUE_SCRIPT", () => app.outputFiles[0].text.replace(/<\/script/gi, "<\\/script"));

// Retain the licenses of every bundled package, including transitive dependencies.
const packages = new Map();
for (const input of [...Object.keys(server.metafile.inputs), ...Object.keys(app.metafile.inputs)]) {
  if (!input.includes("node_modules/")) continue;
  let directory = dirname(join(root, input));
  while (directory !== root) {
    let metadata;
    try { metadata = JSON.parse(await readFile(join(directory, "package.json"), "utf8")); }
    catch (error) { if (error.code !== "ENOENT") throw error; }
    if (metadata?.name && metadata.version) {
      packages.set(`${metadata.name}@${metadata.version}`, directory);
      break;
    }
    const parent = dirname(directory);
    if (parent === directory) throw new Error(`Cannot identify bundled package: ${input}`);
    directory = parent;
  }
}
const notices = [];
for (const [name, directory] of [...packages].sort(([a], [b]) => a.localeCompare(b, "en"))) {
  let license;
  for (const file of ["LICENSE", "LICENSE.txt", "LICENSE.md", "license", "license.md"]) {
    try { license = await readFile(join(directory, file), "utf8"); break; }
    catch (error) { if (error.code !== "ENOENT") throw error; }
  }
  if (!license) throw new Error(`Missing bundled license: ${name}`);
  let notice = "";
  for (const file of ["NOTICE", "NOTICE.txt", "NOTICE.md"]) {
    try { notice = await readFile(join(directory, file), "utf8"); break; }
    catch (error) { if (error.code !== "ENOENT") throw error; }
  }
  notices.push(`${name}\n${[license, notice].filter(Boolean).map(text => text.trim().replace(/\r\n/g, "\n")).join("\n\n")}`);
}
const outputs = new Map([
  ["server.bundle.mjs", server.outputFiles[0].text],
  ["discussion.html", html],
  ["LICENSE.txt", await readFile(join(root, "..", "..", "LICENSE"), "utf8")],
  ["THIRD_PARTY_NOTICES.txt", `${notices.join("\n\n----------------------------------------\n\n")}\n`],
]);
for (const [name, value] of outputs) {
  if (process.argv.includes("--check")) {
    const saved = await readFile(join(root, name), "utf8").catch(error => {
      if (error.code === "ENOENT") return "";
      throw error;
    });
    if (saved.replace(/\r\n/g, "\n") !== value.replace(/\r\n/g, "\n"))
      throw new Error(`Stale plugin artifact: ${name}. Run npm run build in integrations/codex-desktop.`);
  } else await writeFile(join(root, name), value);
}
console.log(process.argv.includes("--check") ? "Plugin artifacts match source." : "Plugin artifacts built.");
